#!/usr/bin/env python3
"""Rebuild the checked-in webfonts; ordinary website builds need no Python.

Requires fonttools==4.68.0 and brotli==1.2.1. Sources are pinned by commit and
SHA-256 in content/assets/fonts/sources.json. Downloads are cached outside the
repository. Run: python3 scripts/prepare-fonts.py --cache /tmp/feng-font-sources
"""
from __future__ import annotations

import argparse
from collections import Counter
from copy import deepcopy
import hashlib
import json
from pathlib import Path
from urllib.request import urlretrieve

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'content/assets/fonts'
FAMILIES = [
    ('wenkai', 'Feng WenKai', 'normal', '400'),
    ('song', 'Feng Song', 'normal', '400 700'),
    ('garamond', 'Feng Garamond', 'normal', '400 700'),
    ('garamond-italic', 'Feng Garamond', 'italic', '400 700'),
    ('serif', 'Feng Serif', 'normal', '400 700'),
    ('serif-italic', 'Feng Serif', 'italic', '400 700'),
]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def unicode_ranges(points):
    ordered = sorted(points)
    ranges = []
    for value in ordered:
        if ranges and value == ranges[-1][1] + 1:
            ranges[-1][1] = value
        else:
            ranges.append([value, value])
    return ','.join(f'U+{a:X}' + (f'-{b:X}' if b != a else '') for a, b in ranges)


def chinese_points():
    # GB2312 provides a content-independent base: all 6,763 encoded Hanzi.
    points = set()
    for first in range(0xB0, 0xF8):
        for second in range(0xA1, 0xFF):
            try:
                points.add(ord(bytes([first, second]).decode('gb2312')))
            except UnicodeDecodeError:
                pass
    frequency = Counter()
    for folder in ['content/posts', 'content/daily-math', 'src', 'scripts']:
        for path in (ROOT / folder).rglob('*'):
            if path.suffix in {'.html', '.json', '.js', '.mjs'}:
                frequency.update(ord(c) for c in path.read_text() if '\u3400' <= c <= '\u9fff')
    points.update(frequency)
    # Common display text loads one reusable package. Remaining GB2312/current
    # characters stay available in non-overlapping unicode-range packages.
    common = set(sorted(frequency, key=lambda cp: (-frequency[cp], cp))[:1600])
    punctuation = set(range(0x3000, 0x3040)) | set(range(0xFF00, 0xFFEF))
    common |= punctuation
    points |= punctuation
    return points, common


def rename_font(font, family, style):
    # Preserve original copyright, license and author name records; modified
    # subsets receive new family/PostScript names instead of Reserved Font Names.
    subfamily = 'Italic' if style == 'italic' else 'Regular'
    postscript = family.replace(' ', '') + '-' + subfamily
    names = {1: family, 2: subfamily, 3: postscript + ';FENG-subset-v1',
             4: family + ' ' + subfamily, 6: postscript, 16: family,
             17: subfamily, 18: family + ' ' + subfamily,
             21: family, 22: subfamily, 25: family.replace(' ', '')}
    font['name'].names = [n for n in font['name'].names if n.nameID not in names]
    for name_id, value in names.items():
        font['name'].setName(value, name_id, 3, 1, 0x409)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cache', type=Path, default=Path('/tmp/feng-font-sources'))
    args = parser.parse_args()
    args.cache.mkdir(parents=True, exist_ok=True)
    sources = json.loads((OUT / 'sources.json').read_text())
    for source in sources:
        target = args.cache / source['file']
        if not target.exists():
            urlretrieve(source['url'], target)
        if digest(target) != source['sha256']:
            raise ValueError(f"Source checksum mismatch: {source['file']}")
        if source['file'].endswith('-OFL.txt'):
            (OUT / source['file']).write_bytes(target.read_bytes())

    cjk, common = chinese_points()
    latin = (set(range(0x20, 0x250)) | set(range(0x370, 0x400)) |
             set(range(0x1E00, 0x2000)) | set(range(0x2000, 0x2070)) |
             set(range(0x20A0, 0x20D0)) | {0x2113, 0x2122, 0x2126, 0x2190, 0x2192, 0x2212})
    css = ['/* Generated by scripts/prepare-fonts.py. See NOTICE.md and OFL files. */']
    manifest = {'schema': 1, 'generator': 'fonttools 4.68.0 / brotli 1.2.1', 'files': []}
    emitted = set()
    for stem, family, style, weight in FAMILIES:
        font = TTFont(args.cache / (stem + '.ttf'), recalcTimestamp=False)
        available = set(font.getBestCmap())
        version = font['name'].getDebugName(5)
        if stem in {'wenkai', 'song'}:
            selected = cjk & available
            first = common & selected
            extra = sorted(selected - first)
            packages = [('common', first)] + [
                (f'cjk-{i // 512 + 1:02}', set(extra[i:i + 512]))
                for i in range(0, len(extra), 512)
            ]
        else:
            packages = [('latin', latin & available)]
        for package, points in packages:
            local = deepcopy(font)
            options = subset.Options()
            options.flavor = 'woff2'
            options.hinting = False
            options.recalc_timestamp = False
            options.name_IDs = ['*']
            options.name_languages = ['*']
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(unicodes=points)
            subsetter.subset(local)
            if 'fvar' in local:
                axes = {'wght': (400, 400, 700)}
                if stem.startswith('serif'):
                    axes['opsz'] = 20
                local = instantiateVariableFont(local, axes, inplace=True)
            rename_font(local, family, style)
            local.flavor = 'woff2'
            filename = f'{stem}-{package}.woff2'
            target = OUT / filename
            local.save(target)
            # Reopen every result: malformed WOFF2 cannot enter the manifest.
            checked = TTFont(target)
            actual = set(checked.getBestCmap())
            if not points <= actual:
                raise ValueError(f'Missing requested characters in {filename}')
            ranges = unicode_ranges(points)
            css.append(f"@font-face{{font-family:'{family}';font-style:{style};font-weight:{weight};font-display:swap;src:url('./{filename}') format('woff2');unicode-range:{ranges};}}")
            manifest['files'].append({'file': filename, 'family': family, 'style': style,
                                      'weight': weight, 'upstreamVersion': version,
                                      'bytes': target.stat().st_size, 'sha256': digest(target),
                                      'characters': len(points), 'unicodeRange': ranges})
            emitted.add(filename)
            print(f'{filename}: {target.stat().st_size:,} bytes / {len(points)} codepoints', flush=True)
    for existing in OUT.glob('*.woff2'):
        if existing.name not in emitted:
            existing.unlink()
    manifest['totalBytes'] = sum(item['bytes'] for item in manifest['files'])
    (OUT / 'fonts.css').write_text('\n'.join(css) + '\n')
    (OUT / 'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(f"Total: {manifest['totalBytes']:,} bytes")


if __name__ == '__main__':
    main()
